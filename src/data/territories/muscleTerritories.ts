export function findMuscleTerritoryByName(name: string): MuscleTerritoryRecord | undefined {
  const cleaned = name
    .replace(/\[[^\]]+\]/g, '')
    .toLowerCase()
    .replace(/\b(left|right|bilateral|muscle)\b/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  const canonical = MUSCLE_TERRITORY_ALIASES[cleaned] ?? cleaned;
  return MUSCLE_TERRITORY_BY_NORMALIZED_NAME.get(canonical);
}
